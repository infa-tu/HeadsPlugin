#pragma once
#include "StdAfx.h"

// 圆周率
const double kPi = 3.14159265358979323846;

//-----------------------------------------------------------------------------
// 圆弧几何数据（用于绘图与剖面线边界）
// 角度采用 AutoCAD 约定：弧度，从 +X 轴逆时针为正
//-----------------------------------------------------------------------------
struct ArcData {
    AcGePoint2d center;      // 圆心
    double      radius;      // 半径(mm)
    double      startAngle;  // 起始角(弧度)
    double      endAngle;    // 终止角(弧度)
};

//-----------------------------------------------------------------------------
// 直线段几何数据
//-----------------------------------------------------------------------------
struct LineData {
    AcGePoint2d start;       // 起点
    AcGePoint2d end;         // 终点
};
